def main() -> None:
    out = ["# Feature Traceability Matrix", "",
           "Generated by `scripts/gen_traceability.py` — edit the script, not this file.", "",
           "Phase 0 baseline (2026-10-28). Nothing below is implemented in EduKhata yet; "
           "\"Existing source\" means code was **read** in that repository, not run or integrated.", "",
           "Columns FE / API / DB / Tests are filled as each feature is built. "
           "Acceptance criteria per module: see `ACCEPTANCE_CRITERIA.md`.", ""]
    counts: dict[str, int] = {}
    for mid, mname, feats in MODULES:
        out += [f"## {mid} — {mname}", "",
                "| ID | Feature | Status | Existing source | Permission | FE | API | DB | Tests |",
                "|---|---|---|---|---|---|---|---|---|"]
        for i, (name, st, src, perm) in enumerate(feats, 1):
            counts[st] = counts.get(st, 0) + 1
            out.append(f"| {mid}-{i:02d} | {name} | {S[st]} | {src} | {perm} | — | — | — | — |")
        out.append("")
    total = sum(counts.values())
    summary = ["## Summary", "", "| Status | Count |", "|---|---|"]
    summary += [f"| {S[k]} | {v} |" for k, v in sorted(counts.items(), key=lambda kv: -kv[1])]
    summary += [f"| **Total** | **{total}** |", ""]
    out[8:8] = summary
    Path(__file__).resolve().parent.parent.joinpath("docs/FEATURE_TRACEABILITY_MATRIX.md").write_text("\n".join(out))
    print(f"{total} features")


if __name__ == "__main__":
    main()
